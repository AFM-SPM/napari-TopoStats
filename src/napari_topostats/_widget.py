def open_config_editor(viewer: Viewer):
    global config_wrapper, full_config_container, comment_descriptions

    if config_wrapper is None:
        print("No config loaded.")
        return
    
    # Keys to include
    EDITABLE_TOP_LEVEL_KEYS = {"filter", "grains"}

